/**
 * Regenerates src/engine/synth/ideal-mesh.data.ts (the ideal-example geometry).
 * Run: npm run research -- ideal
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { expect, it } from "vitest";
import { analyzeFace } from "@/engine/analysis";
import { RUBRIC_VERSION } from "@/engine/psl/rubric";
import { buildIdealModel, checkTargets, optimizeIdeal, syntheticInput } from "@/engine/synth/ideal";

it("optimises the ideal-example geometry and writes the data module", () => {
  const model = buildIdealModel();
  const run = optimizeIdeal({ model, iterations: 16000, onIter: (i, J, fit) => i % 4000 === 0 && console.log(`iter ${i}: J=${J.toFixed(3)} fit=${fit.toFixed(3)}`) });
  const r = analyzeFace(syntheticInput(run.mesh, run.trichion));
  const checks = checkTargets(r);
  const outside = checks.filter((c) => c.inRange === false);
  console.log("outside:", outside.map((c) => `${c.id} ${c.value?.toFixed(3)} (${c.z?.toFixed(2)} u)`).join(", ") || "none");
  console.log("overall index", r.scores.overall?.toFixed(2));
  const disp = run.mesh.map((p, i) => Math.hypot(p.x - model.base[i].x, p.y - model.base[i].y) / 200);
  const meanDisp = disp.reduce((a, b) => a + b, 0) / disp.length;
  const maxDisp = Math.max(...disp);
  const final = run.history[run.history.length - 1];
  const body = `// Generated by tests/research/ideal.test.ts (npm run research -- ideal) — do not edit by hand.
/**
 * Ideal-example geometry for rubric ${RUBRIC_VERSION}: MediaPipe's canonical face,
 * minimally deformed (mirror-symmetric RBF field, ${model.centers.length} centres, radius ${model.radiusIpd} IPD)
 * until the scored frontal measures lie in their reference ranges.
 * Optimiser: (1+1)-ES, ${run.history[run.history.length - 1].iter} iterations, final objective ${final.J.toFixed(4)} (target misfit ${final.fit.toFixed(4)}).
 * Mean vertex displacement ${(meanDisp * 100).toFixed(2)} % IPD, max ${(maxDisp * 100).toFixed(2)} % IPD.
 * Image ${800}×${1000} px, IPD 200 px; [x, y, z] per vertex (z = canonical depth × scale).
 */
export const IDEAL_RUBRIC_VERSION = "${RUBRIC_VERSION}";
export const IDEAL_TRICHION = { x: ${run.trichion.x.toFixed(2)}, y: ${run.trichion.y.toFixed(2)} };
export const IDEAL_STATS = { iterations: ${final.iter}, objective: ${final.J.toFixed(4)}, misfit: ${final.fit.toFixed(4)}, meanDisplacementIpd: ${meanDisp.toFixed(5)}, maxDisplacementIpd: ${maxDisp.toFixed(5)} };
export const IDEAL_MESH: readonly (readonly [number, number, number])[] = [
${run.mesh.map((p) => `  [${p.x.toFixed(2)}, ${p.y.toFixed(2)}, ${p.z.toFixed(2)}],`).join("\n")}
];
`;
  writeFileSync(join(__dirname, "..", "..", "src", "engine", "synth", "ideal-mesh.data.ts"), body);
  expect(r.quality.analyzable).toBe(true);
});
