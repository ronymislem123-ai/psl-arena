// Builds the browser edition (static export for GitHub Pages or any static host).
//   node scripts/build-static.mjs [--base /psl-arena]
// Base path: --base, else PSL_BASE_PATH, else "" (site served from the domain root).
// Output: ./out. Note: Next.js also writes its build cache to .next, so run
// `npm run build` again before `npm start` of the server app.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const argBase = process.argv.indexOf("--base");
let base = argBase > 0 ? process.argv[argBase + 1] ?? "" : process.env.PSL_BASE_PATH ?? "";
base = base.trim().replace(/\/+$/, "");
if (base && !base.startsWith("/")) base = `/${base}`;
const out = join(root, process.env.PSL_STATIC_DIST ?? "out");

console.log(`[build-static] base path: "${base || "/"}"`);
const nextBin = join(root, "node_modules", "next", "dist", "bin", "next");
const res = spawnSync(process.execPath, [nextBin, "build"], { cwd: root, stdio: "inherit", env: { ...process.env, PSL_STATIC: "1", PSL_BASE_PATH: base } });
if (res.status !== 0) process.exit(res.status ?? 1);

// Assets the app needs at runtime; a missing one would only fail on the user's device.
for (const rel of ["index.html", "404.html", "models/face_landmarker.task", "sqljs/sql-wasm-browser.wasm", "mediapipe/wasm"]) {
  if (!existsSync(join(out, rel))) {
    console.error(`[build-static] missing ${rel} in the export`);
    process.exit(1);
  }
}

const version = `psl-arena-static-${Date.now().toString(36)}`;

// Every page (HTML + navigation payloads), all built JS/CSS/fonts and the SQLite
// runtime are precached (about 5 MB), so the whole app opens offline after the first
// visit. The face model and MediaPipe runtime (~30 MB) are cached on first analysis.
const precache = [`${base}/sqljs/sql-wasm-browser.wasm`];
(function walk(dir, rel) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    const r = `${rel}/${f}`;
    if (statSync(p).isDirectory()) {
      if (!["/mediapipe", "/models", "/sqljs", "/icons"].includes(r)) walk(p, r);
    } else if (rel.startsWith("/_next/static")) precache.push(`${base}${r}`);
    else if (rel.startsWith("/_next")) continue;
    else if (f === "index.html") precache.push(`${base}${rel}/`);
    else if (f.endsWith(".txt") || f === "404.html") precache.push(`${base}${r}`);
  }
})(out, "");
const manifest = JSON.parse(readFileSync(join(root, "public", "manifest.webmanifest"), "utf8"));
const at = (p) => `${base}${p}`;
manifest.id = at("/");
manifest.start_url = at("/");
manifest.scope = at("/");
manifest.icons = manifest.icons.map((i) => ({ ...i, src: at(i.src) }));
manifest.shortcuts = (manifest.shortcuts ?? []).map((s) => ({ ...s, url: at(s.url.endsWith("/") ? s.url : `${s.url}/`), icons: s.icons?.map((i) => ({ ...i, src: at(i.src) })) }));
writeFileSync(join(out, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

// Service worker of the browser edition: pages are static shells without personal
// data (that lives in IndexedDB), so pages and assets may be cached for offline use.
writeFileSync(
  join(out, "sw.js"),
  `/* PSL ARENA browser edition service worker (generated by scripts/build-static.mjs). */
const BASE = ${JSON.stringify(base)};
const CACHE = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};
const IMMUTABLE = [BASE + "/_next/static/", BASE + "/mediapipe/", BASE + "/models/", BASE + "/sqljs/", BASE + "/icons/"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => Promise.all(PRECACHE.map((u) => c.add(u).catch(() => undefined))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("psl-arena-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;
  if (IMMUTABLE.some((p) => url.pathname.startsWith(p)) || /\\.(woff2?|ttf)$/.test(url.pathname)) {
    event.respondWith(caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    }));
    return;
  }
  // pages and their navigation payloads: network first, cached copy when offline
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      // offline: the precached copy (query strings such as ?id= or ?_rsc= do not change these static files)
      .catch(async () => (await caches.match(req)) ?? (await caches.match(req, { ignoreSearch: true })) ?? (req.mode === "navigate" ? caches.match(BASE + "/") : Response.error())),
  );
});
`,
);
writeFileSync(join(out, ".nojekyll"), "");

const size = (dir) => readdirSync(dir).reduce((n, f) => {
  const p = join(dir, f);
  const st = statSync(p);
  return n + (st.isDirectory() ? size(p) : st.size);
}, 0);
console.log(`[build-static] done: ${out} (${(size(out) / 1024 / 1024).toFixed(1)} MB), cache ${version}, ${precache.length} precached files`);
