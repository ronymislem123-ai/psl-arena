"""Empirical, spatially correlated landmark-noise model for the Monte-Carlo (engine 2.0).

Usage: python3 -I scripts/research/noise-model.py <imgDir> <detDir> <out.ts|out.json> <name> [<name> …]

For every face, each repeated detection (blur, brightness, contrast, JPEG, small
rotations/scales of the same photo) is mapped back to the source frame with the
inverse of its known transform, normalised by the original's inter-pupillary
distance and centred on the face mean. The deviation fields of all faces are
mirror-augmented (MIRROR index map, x negated) so that the noise statistics do not
prefer a side, then decomposed with an SVD. The leading components (≥ 95 % of the
variance) are kept; the remaining variance per coordinate becomes an independent
residual. A sample is  Σ_k z_k·c_k + r ⊙ ε  (z, ε standard normal), in IPD units,
x right / y down / z depth, upright face frame.

Writing a .ts file emits the engine module (Int16 + per-component scale, base64);
writing .json emits plain arrays for the leave-one-face-out validation.
"""
import base64
import json
import math
import re
import sys
from pathlib import Path

import numpy as np

img_dir, det_dir, out_path, names = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4:]
root = Path(__file__).resolve().parents[2]
canon = (root / "src/engine/landmarks/canonical.ts").read_text()
mirror = [int(x) for x in re.search(r"MIRROR: readonly number\[\] = \[([^\]]*)\]", canon).group(1).split(",")]
assert len(mirror) == 478

fields = []
per_face = {}
for name in names:
    meta = json.loads((img_dir / f"{name}__transforms.json").read_text())
    pts = {}
    for key, fwd in meta["transforms"].items():
        f = det_dir / f"{name}__{key}.json"
        if not f.exists():
            continue
        mesh = json.loads(f.read_text())["mesh"]
        (a, b, tx), (c, d, ty) = fwd
        det = a * d - b * c
        scale = math.sqrt(abs(det))
        back = []
        for x, y, z in mesh:
            u, v = x - tx, y - ty
            back.append(((d * u - b * v) / det, (-c * u + a * v) / det, z / scale))
        pts[key] = np.array(back)
    ref = pts["original"]
    ipd = float(np.linalg.norm(ref[468, :2] - ref[473, :2]))
    stack = np.stack([pts[k] for k in pts]) / ipd  # (V, 478, 3)
    dev = stack - stack.mean(axis=0, keepdims=True)
    per_face[name] = {"variants": int(dev.shape[0]), "ipd": ipd}
    for f in dev:
        fields.append(f)
        m = f[mirror].copy()
        m[:, 0] *= -1
        fields.append(m)

X = np.stack([f.reshape(-1) for f in fields])  # (2·V_total, 1434)
dof = sum(v["variants"] - 1 for v in per_face.values()) * 2
cov_scale = 1 / math.sqrt(dof)
U, S, Vt = np.linalg.svd(X * cov_scale, full_matrices=False)
var = S**2
total = var.sum()
k = int(np.searchsorted(np.cumsum(var) / total, 0.95) + 1)
comps = (S[:k, None] * Vt[:k])  # (k, 1434): sample = z @ comps
resid_var = np.maximum((X * cov_scale) ** 2, 0).sum(axis=0) - (comps**2).sum(axis=0)
resid = np.sqrt(np.maximum(resid_var, 0))

if out_path.suffix == ".json":
    out_path.write_text(json.dumps({"faces": per_face, "k": k, "explained": float(np.cumsum(var)[k - 1] / total), "components": comps.round(7).tolist(), "residual": resid.round(7).tolist()}))
else:
    scales = np.abs(comps).max(axis=1) / 32767
    q = np.round(comps / scales[:, None]).astype("<i2")
    rs = float(np.abs(resid).max() / 32767)
    rq = np.round(resid / rs).astype("<i2")
    b64 = base64.b64encode(q.tobytes()).decode()
    rb64 = base64.b64encode(rq.tobytes()).decode()
    faces = ", ".join(f"{n}: {v['variants']} detections" for n, v in per_face.items())
    out_path.write_text(
        "// Generated by scripts/research/noise-model.py — do not edit by hand.\n"
        "/**\n"
        " * Empirical landmark-noise model: leading principal components of the deviation\n"
        f" * fields of repeated MediaPipe detections ({faces}; mirror-augmented),\n"
        f" * {k} components = {100 * np.cumsum(var)[k - 1] / total:.1f} % of the variance, plus an independent residual.\n"
        " * Units: inter-pupillary distances; layout per component: 478 × (x, y, z).\n"
        " */\n"
        f"export const NOISE_COMPONENTS = {k};\n"
        f"export const NOISE_SCALES: readonly number[] = [{', '.join(f'{s:.6e}' for s in scales)}];\n"
        f"export const NOISE_RESIDUAL_SCALE = {rs:.6e};\n"
        f'export const NOISE_DATA_B64 = "{b64}";\n'
        f'export const NOISE_RESIDUAL_B64 = "{rb64}";\n'
    )
print(json.dumps({"faces": per_face, "k": k, "explained": float(np.cumsum(var)[k - 1] / total), "dof": dof}))
